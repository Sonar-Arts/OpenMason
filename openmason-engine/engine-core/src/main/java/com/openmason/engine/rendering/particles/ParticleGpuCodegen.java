    /**
     * The system-wide sort: the CPU batch's records (copied to the front of {@code blend}) get keys like the GPU
     * pools' ({@code cpu_keys}); every alpha-blended particle — CPU and GPU, all pools — is then sorted back to front
     * in one bitonic sort ({@code sort_pad}, {@code sort_local} with 1024 elements in shared memory, the larger
     * strides in {@code sort_global}), gathered in draw order and drawn with two indirect commands (far / near side
     * of the split plane).
     */
    static String mergedSource() {
        ParticleGpuCodegen g = new ParticleGpuCodegen(null);
        g.mergedProgram();
        return g.out.toString();
    }

    private void mergedProgram() {
        line("~ Generated by ParticleGpuCodegen (OM #100): the system-wide back-to-front sort — do not edit.");
        blank();
        forms(false);
        keyCraft();
        line("kernel merged_begin(1)");
        indent++;
        line("take mctl: i32[] out");
        line("take cpu_count: u32");
        line("mctl[" + M_COUNT + "] = i32(cpu_count)");
        line("mctl[" + M_BEHIND + "] = 0");
        indent--;
        line("end");
        blank();
        line("kernel cpu_keys(" + LOCAL + ")");
        indent++;
        line("take blend: Vertex[] in");
        line("take mkeys: u32[] out");
        line("take mvals: u32[] out");
        line("take mctl: i32[] inout");
        line("take cpu_count: u32");
        line("take cam: vec3");
        line("take forward: vec3");
        line("take split: vec4");
        line("take split_mode: u32");
        line("fix i = gid.x");
        line("if i >= cpu_count");
        indent++;
        line("give");
        indent--;
        line("end");
        line("fix rp = vec3(blend[i].x, blend[i].y, blend[i].z)");
        line("flux behind = split_mode == 0");
        line("if split_mode != 0");
        indent++;
        line("behind = (dot(split.xyz, rp) + split.w >= 0.0) != (split_mode == 1)");
        indent--;
        line("end");
        line("if behind");
        indent++;
        line("atomic_add(mctl[" + M_BEHIND + "], 1)");
        indent--;
        line("end");
        line("mkeys[i] = depth_key(dot(rp - cam, forward), behind)");
        line("mvals[i] = i");
        indent--;
        line("end");
        blank();
        line("~ Keys past the record count sort last (sentinel), so the sort size can be any power of 2 >= it.");
        line("kernel sort_pad(256)");
        indent++;
        line("take mctl: i32[] in");
        line("take mkeys: u32[] out");
        line("take mvals: u32[] out");
        line("take sort_size: u32");
        line("fix i = gid.x");
        line("if i < sort_size and i >= u32(mctl[" + M_COUNT + "])");
        indent++;
        line("mkeys[i] = 0xFFFFFFFF");
        line("mvals[i] = 0");
        indent--;
        line("end");
        indent--;
        line("end");
        blank();
        line("~ Bitonic stages with stride < " + SORT_BLOCK + " in shared memory: stage_k = 0 sorts every block of");
        line("~ " + SORT_BLOCK + " from scratch, otherwise finishes stage stage_k (strides " + (SORT_BLOCK / 2)
                + "..1).");
        line("kernel sort_local(" + (SORT_BLOCK / 2) + ")");
        indent++;
        line("take mkeys: u32[] inout");
        line("take mvals: u32[] inout");
        line("take stage_k: u32");
        line("shared sk: u32[" + SORT_BLOCK + "]");
        line("shared sv: u32[" + SORT_BLOCK + "]");
        line("fix base = wgid.x * " + SORT_BLOCK);
        line("fix t = lid.x");
        int half = SORT_BLOCK / 2;
        line("sk[t] = mkeys[base + t]");
        line("sv[t] = mvals[base + t]");
        line("sk[t + " + half + "] = mkeys[base + t + " + half + "]");
        line("sv[t + " + half + "] = mvals[base + t + " + half + "]");
        line("barrier()");
        line("flux k: u32 = pick(stage_k == 0, 2, stage_k)");
        line("fix k_end: u32 = pick(stage_k == 0, " + SORT_BLOCK + ", stage_k)");
        line("while k <= k_end");
        indent++;
        line("flux j: u32 = pick(stage_k == 0, k / 2, " + half + ")");
        line("while j > 0");
        indent++;
        line("fix a = 2 * j * (t / j) + t % j");
        line("fix b = a + j");
        line("fix up = bit_and(base + a, k) == 0");
        line("fix ka = sk[a]");
        line("fix kb = sk[b]");
        line("if (ka > kb) == up");
        indent++;
        line("fix va = sv[a]");
        line("sk[a] = kb");
        line("sk[b] = ka");
        line("sv[a] = sv[b]");
        line("sv[b] = va");
        indent--;
        line("end");
        line("barrier()");
        line("j = j / 2");
        indent--;
        line("end");
        line("k = k * 2");
        indent--;
        line("end");
        line("mkeys[base + t] = sk[t]");
        line("mvals[base + t] = sv[t]");
        line("mkeys[base + t + " + half + "] = sk[t + " + half + "]");
        line("mvals[base + t + " + half + "] = sv[t + " + half + "]");
        indent--;
        line("end");
        blank();
        line("~ One bitonic compare-exchange pass with stride stage_j >= " + SORT_BLOCK + " (one thread per pair).");
        line("kernel sort_global(256)");
        indent++;
        line("take mkeys: u32[] inout");
        line("take mvals: u32[] inout");
        line("take stage_k: u32");
        line("take stage_j: u32");
        line("take sort_size: u32");
        line("fix t = gid.x");
        line("if t >= sort_size / 2");
        indent++;
        line("give");
        indent--;
        line("end");
        line("fix a = 2 * stage_j * (t / stage_j) + t % stage_j");
        line("fix b = a + stage_j");
        line("fix up = bit_and(a, stage_k) == 0");
        line("fix ka = mkeys[a]");
        line("fix kb = mkeys[b]");
        line("if (ka > kb) == up");
        indent++;
        line("fix va = mvals[a]");
        line("mkeys[a] = kb");
        line("mkeys[b] = ka");
        line("mvals[a] = mvals[b]");
        line("mvals[b] = va");
        indent--;
        line("end");
        indent--;
        line("end");
        blank();
        line("~ The sorted records in draw order.");
        line("kernel gather(" + LOCAL + ")");
        indent++;
        line("take blend: Vertex[] in");
        line("take mvals: u32[] in");
        line("take mctl: i32[] in");
        line("take draw_verts: Vertex[] out");
        line("take sort_size: u32");
        line("fix i = gid.x");
        line("if i >= min(u32(mctl[" + M_COUNT + "]), sort_size)");
        indent++;
        line("give");
        indent--;
        line("end");
        line("draw_verts[i] = blend[mvals[i]]");
        indent--;
        line("end");
        blank();
        line("kernel merged_draw(1)");
        indent++;
        line("take mctl: i32[] in");
        line("take margs: u32[] out");
        line("take sort_size: u32");
        line("fix shown = min(u32(mctl[" + M_COUNT + "]), sort_size)");
        line("fix behind = min(u32(mctl[" + M_BEHIND + "]), shown)");
        line("margs[" + MA_DRAW_BEHIND + "] = 4");
        line("margs[" + (MA_DRAW_BEHIND + 1) + "] = behind");
        line("margs[" + (MA_DRAW_BEHIND + 2) + "] = 0");
        line("margs[" + (MA_DRAW_BEHIND + 3) + "] = 0");
        line("margs[" + MA_DRAW_FRONT + "] = 4");
        line("margs[" + (MA_DRAW_FRONT + 1) + "] = shown - behind");
        line("margs[" + (MA_DRAW_FRONT + 2) + "] = 0");
        line("margs[" + (MA_DRAW_FRONT + 3) + "] = behind");
        indent--;
        line("end");
        blank();
    }

    /** A float literal CEARL reads: plain decimal (no exponent), always with a point, negatives parenthesized. */
    static String lit(float v) {
        if (!Float.isFinite(v)) {
            throw new IllegalArgumentException("non-finite FX constant " + v);
        }
        String s = new BigDecimal(Float.toString(Math.abs(v))).stripTrailingZeros().toPlainString();
        if (!s.contains(".")) {
            s = s + ".0";
        }
        return v < 0f || (v == 0f && 1f / v < 0f) ? "(0.0 - " + s + ")" : s;
    }

    private void line(String text) {
        out.append("    ".repeat(indent)).append(text).append('\n');
    }

    private void blank() {
        out.append('\n');
    }
