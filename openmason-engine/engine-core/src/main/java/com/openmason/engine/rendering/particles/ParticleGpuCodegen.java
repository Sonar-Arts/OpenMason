    private void resetKernel() {
        line("~ Empties the pool: every slot free, every counter zero.");
        line("kernel reset(256)");
        indent++;
        line("take dead: u32[] out");
        line("take ctl: i32[] out");
        line("take inbox_ctl: i32[] out");
        line("fix i = gid.x");
        line("if i < CAP");
        indent++;
        line("dead[i] = CAP - 1 - i");
        indent--;
        line("end");
        line("if i == 0");
        indent++;
        for (int c = 0; c < C_SIZE; c++) {
            line("ctl[" + c + "] = " + (c == C_DEAD ? "i32(CAP)" : "0"));
        }
        line("inbox_ctl[0] = 0");
        indent--;
        line("end");
        indent--;
        line("end");
        blank();
    }

    private void prepKernels() {
        line("~ Last frame's output becomes this frame's input; simulate's indirect dispatch.");
        line("kernel prep_sim(1)");
        indent++;
        line("take ctl: i32[] inout");
        line("take args: u32[] out");
        line("ctl[" + C_IN + "] = ctl[" + C_OUT + "]");
        line("ctl[" + C_OUT + "] = 0");
        line("ctl[" + C_BEHIND + "] = 0");
        line("ctl[" + C_FRONT + "] = 0");
        line("ctl[" + C_EVENTS + "] = 0");
        dispatchArgs(A_SIM, "u32(ctl[" + C_IN + "])");
        indent--;
        line("end");
        blank();
        line("~ The inbox's sub-spawns this frame (parents appended them; overflow past inbox_cap is dropped).");
        line("kernel prep_sub(1)");
        indent++;
        line("take inbox_ctl: i32[] in");
        line("take args: u32[] out");
        line("take inbox_cap: u32");
        dispatchArgs(A_SUB, "min(u32(max(inbox_ctl[0], 0)), inbox_cap)");
        indent--;
        line("end");
        blank();
        line("kernel prep_pack(1)");
        indent++;
        line("take ctl: i32[] in");
        line("take args: u32[] out");
        dispatchArgs(A_PACK, "u32(ctl[" + C_OUT + "])");
        indent--;
        line("end");
        blank();
        line("~ The pool's own two DrawArraysIndirect commands (unmerged mode); empties the inbox.");
        line("kernel prep_draw(1)");
        indent++;
        line("take ctl: i32[] inout");
        line("take args: u32[] out");
        line("take inbox_ctl: i32[] inout");
        line("take inbox_cap: u32");
        line("fix front = u32(ctl[" + C_FRONT + "])");
        line("args[" + A_DRAW_BEHIND + "] = 4");
        line("args[" + (A_DRAW_BEHIND + 1) + "] = u32(ctl[" + C_BEHIND + "])");
        line("args[" + (A_DRAW_BEHIND + 2) + "] = 0");
        line("args[" + (A_DRAW_BEHIND + 3) + "] = 0");
        line("args[" + A_DRAW_FRONT + "] = 4");
        line("args[" + (A_DRAW_FRONT + 1) + "] = front");
        line("args[" + (A_DRAW_FRONT + 2) + "] = 0");
        line("args[" + (A_DRAW_FRONT + 3) + "] = CAP - front");
        line("fix extra = inbox_ctl[0] - i32(inbox_cap)");
        line("if extra > 0");
        indent++;
        line("ctl[" + C_DROPPED + "] = ctl[" + C_DROPPED + "] + extra");
        indent--;
        line("end");
        line("inbox_ctl[0] = 0");
        indent--;
        line("end");
        blank();
    }

    private void dispatchArgs(int at, String count) {
        line("args[" + at + "] = (" + count + " + " + (LOCAL - 1) + ") / " + LOCAL);
        line("args[" + (at + 1) + "] = 1");
        line("args[" + (at + 2) + "] = 1");
    }

    /** Takes of the sub-emitters a kernel can trigger ({@code trigger} = CompiledEffect.TRIGGER_*; -1 = any but birth). */
    private void subTakes(boolean birth) {
        for (int k = 0; k < e.subTrigger.length; k++) {
            boolean isBirth = e.subTrigger[k] == CompiledEffect.TRIGGER_BIRTH;
            if (isBirth == birth) {
                line("take sub" + k + ": SubSpawn[] out");
                line("take sub" + k + "_ctl: i32[] inout");
                line("take sub" + k + "_cap: u32");
            }
        }
    }

    private void simulateKernel() {
        line("~ One step for every live particle: age, die (free its slot), run the update program.");
        line("kernel simulate(" + LOCAL + ")");
        indent++;
        line("take parts: Particle[] inout");
        line("take alive_in: u32[] in");
        line("take alive_out: u32[] out");
        line("take dead: u32[] out");
        line("take ctl: i32[] inout");
        line("take events: Event[] out");
        line("take owner_live: i32[] inout");
        line("take heights: f32[] in");
        line("take volume: u32[] in");
        subTakes(false);
        line("take dt: f32");
        line("take wind: vec3");
        line("take shift: vec3");
        line("take want_events: u32");
        line("take event_cap: u32");
        line("take field: vec4");
        line("take field_size: vec4");
        line("take vol_origin: vec4");
        line("take vol_size: vec4");
        line("fix i = gid.x");
        line("if i >= u32(ctl[" + C_IN + "])");
        indent++;
        line("give");
        indent--;
        line("end");
        line("fix slot = alive_in[i]");
        line("flux p = parts[slot]");
        line("p.px = p.px + shift.x");
        line("p.py = p.py + shift.y");
        line("p.pz = p.pz + shift.z");
        line("fix aged = p.age + dt");
        line("if aged * p.inv_life >= 1.0");
        indent++;
        event("0", "p.px", "p.py", "p.pz", "p.vx", "p.vy", "p.vz", "p.owner != 0");
        subsFor(CompiledEffect.TRIGGER_DEATH, "p.px", "p.py", "p.pz", "p.vx", "p.vy", "p.vz", null);
        ownerLive("0 - 1");
        line("fix d = atomic_add(ctl[" + C_DEAD + "], 1)");
        line("dead[u32(d)] = slot");
        line("give");
        indent--;
        line("end");
        line("p.age = aged");
        program(e.updateProgram, "u");
        line("parts[slot] = p");
        line("fix o = atomic_add(ctl[" + C_OUT + "], 1)");
        line("alive_out[u32(o)] = slot");
        indent--;
        line("end");
        blank();
    }

    private void ownerLive(String delta) {
        line("if p.owner != 0 and shr(p.owner, 8) < count(owner_live)");
        indent++;
        line("atomic_add(owner_live[shr(p.owner, 8)], " + delta + ")");
        indent--;
        line("end");
    }

    private void spawnKernel() {
        line("~ Expands this frame's spawn requests: thread i finds its request (binary search over 'first'),");
        line("~ pops a free slot and initializes a particle exactly as ParticleSystem.spawn does.");
        line("kernel spawn(" + LOCAL + ")");
        indent++;
        line("take parts: Particle[] inout");
        line("take reqs: Spawn[] in");
        line("take dead: u32[] in");
        line("take alive_out: u32[] out");
        line("take ctl: i32[] inout");
        line("take owner_live: i32[] inout");
        subTakes(true);
        line("take req_count: u32");
        line("take total: u32");
        line("take dt: f32");
        line("take wind: vec3");
        line("fix i = gid.x");
        line("if i >= total");
        indent++;
        line("give");
        indent--;
        line("end");
        line("flux lo: u32 = 0");
        line("flux hi = req_count - 1");
        line("while lo < hi");
        indent++;
        line("fix mid = (lo + hi + 1) / 2");
        line("if reqs[mid].first <= i");
        indent++;
        line("lo = mid");
        indent--;
        line("else");
        indent++;
        line("hi = mid - 1");
        indent--;
        line("end");
        indent--;
        line("end");
        line("fix r = reqs[lo]");
        line("fix k = i - r.first");
        initParticle("r.ox", "r.oy", "r.oz", "vec3(r.dx, r.dy, r.dz)", "r.speed", "r.size",
                "vec3(r.ivx, r.ivy, r.ivz)", "r.pre", "r.tint", "r.owner", "bit_xor(r.seed, k * 0x9E3779B9)");
        indent--;
        line("end");
        blank();
    }

    private void subspawnKernel() {
        line("~ Children parent particles appended to this pool's inbox: born at the parent's position with its");
        line("~ inherited velocity, along this effect's own direction (as ParticleSystem's sub-emitter events).");
        line("kernel subspawn(" + LOCAL + ")");
        indent++;
        line("take parts: Particle[] inout");
        line("take inbox: SubSpawn[] in");
        line("take inbox_ctl: i32[] in");
        line("take dead: u32[] in");
        line("take alive_out: u32[] out");
        line("take ctl: i32[] inout");
        line("take owner_live: i32[] inout");
        subTakes(true);
        line("take inbox_cap: u32");
        line("take dt: f32");
        line("take wind: vec3");
        line("fix i = gid.x");
        line("if i >= min(u32(max(inbox_ctl[0], 0)), inbox_cap)");
        indent++;
        line("give");
        indent--;
        line("end");
        line("fix r = inbox[i]");
        initParticle("r.x", "r.y", "r.z", "vec3(" + lit(e.dirX) + ", " + lit(e.dirY) + ", " + lit(e.dirZ) + ")",
                "1.0", "1.0", "vec3(r.vx, r.vy, r.vz)", "0.0", "0xFFFFFFFF", "r.owner", "r.seed");
        indent--;
        line("end");
        blank();
    }

    /**
     * {@link ParticleSystem}'s spawn initializer: pops a free slot (counted as dropped when none), shape, spread
     * cone, speed, lifetime, sizes, rotation, colour jitter, frame pick, custom defaults, the spawn program, BIRTH
     * sub-emitters; then pushes the slot to the live list.
     */
    private void initParticle(String ox, String oy, String oz, String dir, String speedScale, String sizeScale,
                              String inherit, String pre, String tint, String owner, String seed) {
        line("fix popped = atomic_add(ctl[" + C_DEAD + "], 0 - 1)");
        line("if popped <= 0");
        indent++;
        line("atomic_add(ctl[" + C_DEAD + "], 1)");
        line("atomic_add(ctl[" + C_DROPPED + "], 1)");
        line("give");
        indent--;
        line("end");
        line("fix slot = dead[u32(popped - 1)]");
        line("flux p = parts[slot]");
        line("flux rng = pcg(" + seed + ")");
        line("fix dir = " + dir);
        line("fix helper = pick(abs(dir.x) < 0.9, vec3(1.0, 0.0, 0.0), vec3(0.0, 1.0, 0.0))");
        line("fix ub = normalize(cross(dir, helper))");
        line("fix wb = cross(dir, ub)");
        line("flux sp = vec3(0.0)");
        switch (e.shape) {
            case POINT -> { }
            case SPHERE -> {
                rand("rz");
                rand("rphi");
                rand("rr");
                line("fix cz = 2.0 * rz - 1.0");
                line("fix phi = rphi * 6.2831855");
                line("fix sr = sqrt(max(0.0, 1.0 - cz * cz))");
                line("fix rad = " + lit(e.radius) + " * pow(rr, 0.33333334)");
                line("sp = vec3(cos(phi) * sr * rad, cz * rad, sin(phi) * sr * rad)");
            }
            case BOX -> {
                rand("bx");
                rand("by");
                rand("bz");
                line("sp = vec3((bx * 2.0 - 1.0) * " + lit(e.halfX) + ", (by * 2.0 - 1.0) * " + lit(e.halfY)
                        + ", (bz * 2.0 - 1.0) * " + lit(e.halfZ) + ")");
            }
            case DISC -> {
                rand("rphi");
                rand("rr");
                line("fix phi = rphi * 6.2831855");
                line("fix rad = " + lit(e.radius) + " * sqrt(rr)");
                line("sp = vec3(cos(phi) * rad, 0.0, sin(phi) * rad)");
            }
        }
        rand("rcos");
        rand("rphi2");
        rand("rspeed");
        line("fix cos_t = 1.0 - rcos * " + lit(1f - e.cosSpread));
        line("fix sin_t = sqrt(max(0.0, 1.0 - cos_t * cos_t))");
        line("fix phi2 = rphi2 * 6.2831855");
        line("fix speed = (" + lit(e.speedMin) + " + rspeed * " + lit(e.speedSpan) + ") * " + speedScale);
        line("fix lv = (dir * cos_t + ub * (cos(phi2) * sin_t) + wb * (sin(phi2) * sin_t)) * speed + " + inherit);
        rand("rborn");
        line("fix born = rborn * " + pre);
        line("p.px = " + ox + " + sp.x + lv.x * born");
        line("p.py = " + oy + " + sp.y + lv.y * born");
        line("p.pz = " + oz + " + sp.z + lv.z * born");
        line("p.vx = lv.x");
        line("p.vy = lv.y");
        line("p.vz = lv.z");
        line("p.age = born");
        rand("rlife");
        line("p.inv_life = 1.0 / (" + lit(e.lifeMin) + " + rlife * " + lit(e.lifeSpan) + ")");
        rand("rs0");
        rand("rs1");
        line("p.size0 = (" + lit(e.startSizeMin) + " + rs0 * " + lit(e.startSizeSpan) + ") * " + sizeScale);
        line("p.size1 = (" + lit(e.endSizeMin) + " + rs1 * " + lit(e.endSizeSpan) + ") * " + sizeScale);
        rand("rrot");
        rand("rspin");
        line("p.rot = " + lit(e.rotMin) + " + rrot * " + lit(e.rotSpan));
        line("p.spin = " + lit(e.spinMin) + " + rspin * " + lit(e.spinSpan));
        line("fix base_tint: u32 = " + tint);
        if (e.colorJitter > 0f) {
            rand("rjit");
            line("fix scale = 1.0 - " + lit(e.colorJitter) + " * rjit");
            line("fix tr = min(255.0, floor(f32(shr(base_tint, 24)) * scale + 0.5))");
            line("fix tg = min(255.0, floor(f32(bit_and(shr(base_tint, 16), 255)) * scale + 0.5))");
            line("fix tb = min(255.0, floor(f32(bit_and(shr(base_tint, 8), 255)) * scale + 0.5))");
            line("p.tint = bit_or(bit_or(shl(u32(tr), 24), shl(u32(tg), 16)), bit_or(shl(u32(tb), 8),"
                    + " bit_and(base_tint, 255)))");
        } else {
            line("p.tint = base_tint");
        }
        line("p.owner = " + owner);
        if (e.textured && !e.animate && e.frameCount > 1) {
            rand("rframe");
            line("p.frame = min(u32(rframe * " + lit(e.frameCount) + "), " + (e.frameCount - 1) + ")");
        } else {
            line("p.frame = 0");
        }
        for (int k = 0; k < e.customDefaults.length; k++) {
            line("p.c" + k + " = " + lit(e.customDefaults[k]));
        }
        line("p.seed = pcg(rng)");
        if (e.spawnProgram != null) {
            program(e.spawnProgram, "s");
        }
        subsFor(CompiledEffect.TRIGGER_BIRTH, "p.px", "p.py", "p.pz", "p.vx", "p.vy", "p.vz", null);
        ownerLive("1");
        line("parts[slot] = p");
        line("fix o = atomic_add(ctl[" + C_OUT + "], 1)");
        line("alive_out[u32(o)] = slot");
    }

    /** One random draw from the spawn stream into a new local. */
    private void rand(String name) {
        line("rng = pcg(rng)");
        line("fix " + name + " = u01(rng)");
    }

    /**
     * Appends the sub-emitter children of every sub-emitter with {@code trigger} to their target's inbox: the
     * sub-emitter's count (or, for TRAIL, {@code rate × dt} rounded stochastically with {@code rand}), each child at
     * the parent's position with {@code inherit ×} its velocity and a derived owner.
     */
    private void subsFor(int trigger, String x, String y, String z, String vx, String vy, String vz, String rand) {
        for (int k = 0; k < e.subTrigger.length; k++) {
            if (e.subTrigger[k] != trigger) {
                continue;
            }
            int id = unique++;
            String n = "sn" + id, q = "sq" + id;
            if (trigger == CompiledEffect.TRIGGER_TRAIL) {
                line("fix se" + id + " = " + lit(e.subRate[k]) + " * dt");
                line(rand + " = pcg(" + rand + ")");
                line("fix " + n + " = u32(floor(se" + id + ")) + pick(u01(" + rand + ") < se" + id + " - floor(se" + id
                        + "), u32(1), u32(0))");
            } else {
                line("fix " + n + ": u32 = " + e.subCount[k]);
            }
            float inherit = e.subInherit[k];
            line("flux " + q + ": u32 = 0");
            line("while " + q + " < " + n);
            indent++;
            line("fix si" + id + " = u32(atomic_add(sub" + k + "_ctl[0], 1))");
            line("if si" + id + " < sub" + k + "_cap");
            indent++;
            String r = "sub" + k + "[si" + id + "]";
            line(r + ".x = " + x);
            line(r + ".y = " + y);
            line(r + ".z = " + z);
            line(r + ".vx = " + vx + " * " + lit(inherit));
            line(r + ".vy = " + vy + " * " + lit(inherit));
            line(r + ".vz = " + vz + " * " + lit(inherit));
            line(r + ".owner = pick(p.owner == 0, 0, bit_or(p.owner, 255))");
            line(r + ".seed = pcg(bit_xor(p.seed, (" + q + " + 1) * 0x9E3779B9 + " + (k * 7919) + "))");
            indent--;
            line("end");
            line(q + " = " + q + " + 1");
            indent--;
            line("end");
        }
    }

    private void packKernel() {
        line("~ Culls the live particles; unmerged: records two-ended into verts (far side of the split plane from");
        line("~ the start, near side from the end); merged: records + back-to-front keys into the shared sort.");
        line("kernel pack(" + LOCAL + ")");
        indent++;
        line("take parts: Particle[] in");
        line("take alive_out: u32[] in");
        line("take ctl: i32[] inout");
        line("take verts: Vertex[] out");
        line("take blend: Vertex[] out");
        line("take mkeys: u32[] out");
        line("take mvals: u32[] out");
        line("take mctl: i32[] inout");
        line("take frames: vec4[" + frameVec4s(e) + "]");
        line("take planes: vec4[6]");
        line("take offset: vec3");
        line("take cam: vec3");
        line("take forward: vec3");
        line("take max_dist2: f32");
        line("take split: vec4");
        line("take split_mode: u32");
        line("take merged: u32");
        line("fix i = gid.x");
        line("if i >= u32(ctl[" + C_OUT + "])");
        indent++;
        line("give");
        indent--;
        line("end");
        line("fix slot = alive_out[i]");
        line("fix p = parts[slot]");
        line("fix t = p.age * p.inv_life");
        line("fix size = (p.size0 + (p.size1 - p.size0) * t) * size_scale(t)");
        line("if size <= 0.0");
        indent++;
        line("give");
        indent--;
        line("end");
        line("fix rp = vec3(p.px, p.py, p.pz) + offset");
        line("fix to_cam = rp - cam");
        line("if dot(to_cam, to_cam) > max_dist2");
        indent++;
        line("give");
        indent--;
        line("end");
        line("flux bound = size * 0.70710677");
        if (e.orientation == ParticleEffect.Orientation.VELOCITY.ordinal()) {
            line("bound = bound + length(vec3(p.vx, p.vy, p.vz)) * " + lit(e.stretch));
        }
        line("for q in 0..6");
        indent++;
        line("if dot(planes[q].xyz, rp) + planes[q].w < 0.0 - bound");
        indent++;
        line("give");
        indent--;
        line("end");
        indent--;
        line("end");
        line("~ No split plane: everything is 'behind' (drawn by drawBehind/drawAll, like the CPU path).");
        line("flux behind = split_mode == 0");
        line("if split_mode != 0");
        indent++;
        line("fix side = dot(split.xyz, rp) + split.w >= 0.0");
        line("behind = side != (split_mode == 1)");
        indent--;
        line("end");
        line("if merged != 0");
        indent++;
        line("fix k = u32(atomic_add(mctl[" + M_COUNT + "], 1))");
        line("if behind");
        indent++;
        line("atomic_add(mctl[" + M_BEHIND + "], 1)");
        indent--;
        line("end");
        line("mkeys[k] = depth_key(dot(to_cam, forward), behind)");
        line("mvals[k] = k");
        writeVertex("blend", "k", "rp", "size", "t");
        indent--;
        line("else");
        indent++;
        line("flux k: u32 = 0");
        line("if behind");
        indent++;
        line("k = u32(atomic_add(ctl[" + C_BEHIND + "], 1))");
        indent--;
        line("else");
        indent++;
        line("k = CAP - 1 - u32(atomic_add(ctl[" + C_FRONT + "], 1))");
        indent--;
        line("end");
        writeVertex("verts", "k", "rp", "size", "t");
        indent--;
        line("end");
        indent--;
        line("end");
        blank();
    }

    /** Inline record build ({@link ParticleBatchBuilder#pack} semantics) into {@code buffer[index]}. */
    private void writeVertex(String buffer, String index, String rp, String size, String t) {
        int id = unique++;
        String ck = "ck" + id, tc = "tc" + id, al = "al" + id, rgb = "rgb" + id, an = "an" + id;
        line("fix " + ck + " = color_at(" + t + ")");
        line("fix " + tc + " = vec4(f32(shr(p.tint, 24)), f32(bit_and(shr(p.tint, 16), 255)),"
                + " f32(bit_and(shr(p.tint, 8), 255)), f32(bit_and(p.tint, 255))) * 0.003921569");
        line("fix " + al + " = " + ck + ".w * " + tc + ".w * fade(" + t + ")");
        line("fix " + rgb + " = vec3(" + ck + ".x * " + tc + ".x, " + ck + ".y * " + tc + ".y, " + ck + ".z * " + tc
                + ".z) * " + al);
        line("flux " + an + " = p.rot");
        line("if " + an + " > 3.1415927 or " + an + " < -3.1415927");
        indent++;
        line(an + " = " + an + " - 6.2831855 * floor((" + an + " + 3.1415927) / 6.2831855)");
        indent--;
        line("end");
        int flags = (e.emissive ? ParticleVertexFormat.FLAG_EMISSIVE : 0)
                | (e.orientation << ParticleVertexFormat.ORIENTATION_SHIFT);
        String frameFlags;
        if (!e.textured) {
            frameFlags = Long.toString((e.frames[0] & 0xFFFFL) | ((long) flags << 16));
        } else {
            String pk = "pk" + id, fv = "fv" + id, fs = "fs" + id;
            if (e.animate) {
                line("fix " + pk + " = min(u32(" + t + " * " + lit(e.frameCount) + "), " + (e.frameCount - 1) + ")");
            } else {
                line("fix " + pk + " = min(p.frame, " + (e.frameCount - 1) + ")");
            }
            line("fix " + fv + " = frames[" + pk + " / 4]");
            line("fix " + fs + " = " + pk + " % 4");
            frameFlags = "bit_or(u32(pick(" + fs + " == 0, " + fv + ".x, pick(" + fs + " == 1, " + fv + ".y, pick(" + fs
                    + " == 2, " + fv + ".z, " + fv + ".w)))), " + ((long) flags << 16) + ")";
        }
        float stretch = e.orientation == ParticleEffect.Orientation.VELOCITY.ordinal() ? e.stretch : 0f;
        String v = buffer + "[" + index + "]";
        line(v + ".x = " + rp + ".x");
        line(v + ".y = " + rp + ".y");
        line(v + ".z = " + rp + ".z");
        line(v + ".color = pack_unorm4(clamp(vec4(" + rgb + ", " + al + " * " + lit(1f - e.additive)
                + "), 0.0, 1.0))");
        line(v + ".size_rot = pack_half2(vec2(" + size + ", " + an + "))");
        line(v + ".frame_flags = " + frameFlags);
        line(v + ".axis_xy = pack_half2(vec2(p.vx * " + lit(stretch) + ", p.vy * " + lit(stretch) + "))");
        line(v + ".axis_z_soft = pack_half2(vec2(p.vz * " + lit(stretch) + ", " + lit(e.softness) + "))");
    }

    /** An event record (kind 0 death, 1 impact) if the host wants events and there is room. */
    private void event(String kind, String x, String y, String z, String vx, String vy, String vz, String extra) {
        line("if want_events != 0 and " + extra);
        indent++;
        line("fix ev = u32(atomic_add(ctl[" + C_EVENTS + "], 1))");
        line("if ev < event_cap");
        indent++;
        line("events[ev].owner = p.owner");
        line("events[ev].kind = " + kind);
        line("events[ev].x = " + x);
        line("events[ev].y = " + y);
        line("events[ev].z = " + z);
        line("events[ev].vx = " + vx);
        line("events[ev].vy = " + vy);
        line("events[ev].vz = " + vz);
        indent--;
        line("end");
        indent--;
        line("end");
    }

