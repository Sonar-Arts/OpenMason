    /** Translates a compiled stage program over the local {@code p} (uniform part, then lanes). */
    private void program(FxProgram prog, String curvePrefix) {
        line("~ " + prog.stage + " program: " + prog.uniformInstructions() + " uniform + " + prog.laneInstructions()
                + " lane instructions");
        for (int r = 0; r < prog.uniformRegisters; r++) {
            line("flux u" + r + ": f32 = 0.0");
        }
        for (int r = 0; r < prog.laneRegisters; r++) {
            line("flux r" + r + ": f32 = 0.0");
        }
        boolean random = uses(prog, FxVm.RANDOM) || uses(prog, FxVm.TRAIL);
        if (random) {
            line("flux prng = p.seed");
        }
        code(prog, prog.uniformCode, "u", curvePrefix);
        code(prog, prog.laneCode, "r", curvePrefix);
        if (random) {
            line("p.seed = prng");
        }
    }

    private static boolean uses(FxProgram p, int opcode) {
        for (int[] code : new int[][]{p.uniformCode, p.laneCode}) {
            for (int pc = 0; pc < code.length; pc += FxVm.LENGTH[code[pc]]) {
                if (code[pc] == opcode) {
                    return true;
                }
            }
        }
        return false;
    }

    private void code(FxProgram prog, int[] code, String reg, String curvePrefix) {
        for (int pc = 0; pc < code.length; pc += FxVm.LENGTH[code[pc]]) {
            int op = code[pc];
            String d = FxVm.LENGTH[op] > 1 ? reg + code[pc + 1] : "";
            switch (op) {
                case FxVm.CONST -> line(d + " = " + lit(prog.constants[code[pc + 2]]));
                case FxVm.DT -> line(d + " = dt");
                case FxVm.WINDX -> line(d + " = wind.x");
                case FxVm.WINDY -> line(d + " = wind.y");
                case FxVm.WINDZ -> line(d + " = wind.z");
                case FxVm.RANDOM -> {
                    line("prng = pcg(prng)");
                    line(d + " = u01(prng)");
                }
                case FxVm.LOAD -> line(d + " = p." + column(code[pc + 2]));
                case FxVm.STORE -> line("p." + column(code[pc + 1]) + " = " + reg + code[pc + 2]);
                case FxVm.BCAST -> line(d + " = u" + code[pc + 2]);
                case FxVm.ADD -> line(d + " = " + r(reg, code[pc + 2]) + " + " + r(reg, code[pc + 3]));
                case FxVm.SUB -> line(d + " = " + r(reg, code[pc + 2]) + " - " + r(reg, code[pc + 3]));
                case FxVm.MUL -> line(d + " = " + r(reg, code[pc + 2]) + " * " + r(reg, code[pc + 3]));
                case FxVm.DIV -> line(d + " = " + r(reg, code[pc + 2]) + " / " + r(reg, code[pc + 3]));
                case FxVm.MIN -> line(d + " = min(" + r(reg, code[pc + 2]) + ", " + r(reg, code[pc + 3]) + ")");
                case FxVm.MAX -> line(d + " = max(" + r(reg, code[pc + 2]) + ", " + r(reg, code[pc + 3]) + ")");
                case FxVm.NEG -> line(d + " = 0.0 - " + r(reg, code[pc + 2]));
                case FxVm.ABS -> line(d + " = abs(" + r(reg, code[pc + 2]) + ")");
                case FxVm.SQRT -> line(d + " = sqrt(" + r(reg, code[pc + 2]) + ")");
                case FxVm.SIN -> line(d + " = sin(" + r(reg, code[pc + 2]) + ")");
                case FxVm.COS -> line(d + " = cos(" + r(reg, code[pc + 2]) + ")");
                case FxVm.EXP -> line(d + " = exp(" + r(reg, code[pc + 2]) + ")");
                case FxVm.FLOOR -> line(d + " = floor(" + r(reg, code[pc + 2]) + ")");
                case FxVm.SAFEINV -> line(d + " = pick(" + r(reg, code[pc + 2]) + " > 0.000000000001, 1.0 / max("
                        + r(reg, code[pc + 2]) + ", 0.000000000001), 0.0)");
                case FxVm.LERP -> line(d + " = " + r(reg, code[pc + 2]) + " + (" + r(reg, code[pc + 3]) + " - "
                        + r(reg, code[pc + 2]) + ") * " + r(reg, code[pc + 4]));
                case FxVm.CLAMP -> line(d + " = min(max(" + r(reg, code[pc + 2]) + ", " + r(reg, code[pc + 3])
                        + "), " + r(reg, code[pc + 4]) + ")");
                case FxVm.CURVE -> line(d + " = curve_" + curvePrefix + code[pc + 3] + "(" + r(reg, code[pc + 2]) + ")");
                case FxVm.NOISE -> line(d + " = noise_full(vec3(" + r(reg, code[pc + 2]) + ", " + r(reg, code[pc + 3])
                        + ", " + r(reg, code[pc + 4]) + ")).x");
                case FxVm.CURL -> {
                    String c = "curl_" + reg + pc;
                    line("fix " + c + " = curl3(vec3(" + r(reg, code[pc + 4]) + ", " + r(reg, code[pc + 5]) + ", "
                            + r(reg, code[pc + 6]) + "))");
                    line(r(reg, code[pc + 1]) + " = " + c + ".x");
                    line(r(reg, code[pc + 2]) + " = " + c + ".y");
                    line(r(reg, code[pc + 3]) + " = " + c + ".z");
                }
                case FxVm.COLLIDE -> collide(r(reg, code[pc + 1]), r(reg, code[pc + 2]), r(reg, code[pc + 3]));
                case FxVm.TRAIL -> subsFor(CompiledEffect.TRIGGER_TRAIL, "p.px", "p.py", "p.pz", "p.vx", "p.vy", "p.vz",
                        "prng");
                default -> throw new IllegalArgumentException(e.source.name() + ": FX instruction "
                        + FxVm.NAMES[op] + " has no GPU form (emitter-stage op)");
            }
        }
    }

    private static String r(String reg, int n) {
        return reg + n;
    }

    /**
     * The built-in {@code move} module's COLLIDE on the GPU, {@link ParticleSystem}'s collider ported: sub-steps of
     * at most {@value ParticleSystem#COLLISION_STEP} blocks (≤ 16), each axis resolved separately against the host's
     * voxel volume (partial-height cells blocking their bottom slab) probing the particle's edge, landing snapped onto
     * the slab top, bounce/friction/settling, an impact event and COLLISION sub-emitters above 1 block/s. Without a
     * volume, the host height field acts as solid ground below its heights; without either, free flight.
     */
    private void collide(String nvx, String nvy, String nvz) {
        line("~ move");
        if (!e.collides) {
            line("p.px = p.px + " + nvx + " * dt");
            line("p.py = p.py + " + nvy + " * dt");
            line("p.pz = p.pz + " + nvz + " * dt");
        } else {
            line("if vol_origin.w > 0.5 or field.w > 0.5");
            indent++;
            line("fix ct = p.age * p.inv_life");
            line("fix radius = 0.5 * (p.size0 + (p.size1 - p.size0) * ct) * size_scale(ct)");
            line("fix ddx = " + nvx + " * dt");
            line("fix ddy = " + nvy + " * dt");
            line("fix ddz = " + nvz + " * dt");
            line("fix longest = max(abs(ddx), max(abs(ddy), abs(ddz)))");
            line("fix steps: u32 = pick(longest > " + lit(COLLISION_STEP) + ", min(16, u32(ceil(longest / "
                    + lit(COLLISION_STEP) + "))), 1)");
            line("fix stx = ddx / f32(steps)");
            line("fix sty = ddy / f32(steps)");
            line("fix stz = ddz / f32(steps)");
            line("flux mx = p.px");
            line("flux my = p.py");
            line("flux mz = p.pz");
            line("flux hit_x = false");
            line("flux hit_y = false");
            line("flux hit_z = false");
            line("flux impact = 0.0");
            line("flux s: u32 = 0");
            line("while s < steps");
            indent++;
            // x
            line("if not hit_x and stx != 0.0");
            indent++;
            line("fix tx = mx + stx");
            blocked("tx + pick(stx < 0.0, 0.0 - radius, radius)", "my", "mz", "bx");
            line("if bx");
            indent++;
            line("hit_x = true");
            line("impact = max(impact, abs(" + nvx + "))");
            line(nvx + " = 0.0 - " + nvx + " * " + lit(e.bounce));
            indent--;
            line("else");
            indent++;
            line("mx = tx");
            indent--;
            line("end");
            indent--;
            line("end");
            // y
            line("if not hit_y and sty != 0.0");
            indent++;
            line("fix ty = my + sty");
            blocked("mx", "ty + pick(sty < 0.0, 0.0 - radius, radius)", "mz", "by");
            line("if by");
            indent++;
            line("hit_y = true");
            line("impact = max(impact, abs(" + nvy + "))");
            line("fix landed = sty < 0.0");
            line(nvy + " = 0.0 - " + nvy + " * " + lit(e.bounce));
            line("if landed");
            indent++;
            line("my = min(my, by_top + radius + 0.0001)");
            line(nvx + " = " + nvx + " * " + lit(e.friction));
            line(nvz + " = " + nvz + " * " + lit(e.friction));
            line("if " + nvy + " < 0.5");
            indent++;
            line(nvy + " = 0.0");
            indent--;
            line("end");
            indent--;
            line("end");
            indent--;
            line("else");
            indent++;
            line("my = ty");
            indent--;
            line("end");
            indent--;
            line("end");
            // z
            line("if not hit_z and stz != 0.0");
            indent++;
            line("fix tz = mz + stz");
            blocked("mx", "my", "tz + pick(stz < 0.0, 0.0 - radius, radius)", "bz");
            line("if bz");
            indent++;
            line("hit_z = true");
            line("impact = max(impact, abs(" + nvz + "))");
            line(nvz + " = 0.0 - " + nvz + " * " + lit(e.bounce));
            indent--;
            line("else");
            indent++;
            line("mz = tz");
            indent--;
            line("end");
            indent--;
            line("end");
            line("s = s + 1");
            indent--;
            line("end");
            line("p.px = mx");
            line("p.py = my");
            line("p.pz = mz");
            line("if impact > " + lit(ParticleSystem.IMPACT_SPEED));
            indent++;
            event("1", "mx", "my", "mz", nvx, nvy, nvz, "p.owner != 0");
            subsFor(CompiledEffect.TRIGGER_COLLISION, "mx", "my", "mz", nvx, nvy, nvz, null);
            indent--;
            line("end");
            indent--;
            line("else");
            indent++;
            line("p.px = p.px + " + nvx + " * dt");
            line("p.py = p.py + " + nvy + " * dt");
            line("p.pz = p.pz + " + nvz + " * dt");
            indent--;
            line("end");
        }
        line("p.vx = " + nvx);
        line("p.vy = " + nvy);
        line("p.vz = " + nvz);
    }

    /**
     * {@code ParticleSystem.blocked}: is the anchor-relative point inside a cell's blocking slab? Declares
     * {@code <name>} (bool) and {@code <name>_top} (the slab's top, anchor-relative). Volume cells are bytes
     * (solid height × 255, x fastest, then z, then y), four per u32.
     */
    private void blocked(String x, String y, String z, String name) {
        line("flux " + name + " = false");
        line("flux " + name + "_top = 0.0");
        line("if vol_origin.w > 0.5");
        indent++;
        line("fix " + name + "_cx = floor(" + x + " - vol_origin.x)");
        line("fix " + name + "_cy = floor(" + y + " - vol_origin.y)");
        line("fix " + name + "_cz = floor(" + z + " - vol_origin.z)");
        line("if " + name + "_cx >= 0.0 and " + name + "_cy >= 0.0 and " + name + "_cz >= 0.0 and " + name
                + "_cx < vol_size.x and " + name + "_cy < vol_size.y and " + name + "_cz < vol_size.z");
        indent++;
        line("fix " + name + "_i = u32((" + name + "_cy * vol_size.z + " + name + "_cz) * vol_size.x + " + name + "_cx)");
        line("fix " + name + "_h = f32(bit_and(shr(volume[" + name + "_i / 4], (" + name + "_i % 4) * 8), 255))"
                + " * 0.003921569");
        line("fix " + name + "_fy = (" + y + " - vol_origin.y) - " + name + "_cy");
        line("if " + name + "_h > 0.0 and (" + name + "_h >= 1.0 or " + name + "_fy < " + name + "_h)");
        indent++;
        line(name + " = true");
        line(name + "_top = vol_origin.y + " + name + "_cy + min(" + name + "_h, 1.0)");
        indent--;
        line("end");
        indent--;
        line("end");
        indent--;
        line("elif field.w > 0.5");
        indent++;
        line("fix " + name + "_gx = floor((" + x + " - field.x) / field.z)");
        line("fix " + name + "_gz = floor((" + z + " - field.y) / field.z)");
        line("if " + name + "_gx >= 0.0 and " + name + "_gz >= 0.0 and " + name + "_gx < field_size.x and " + name
                + "_gz < field_size.y");
        indent++;
        line("fix " + name + "_g = heights[u32(" + name + "_gz * field_size.x + " + name + "_gx)] - field_size.z");
        line("if " + y + " < " + name + "_g");
        indent++;
        line(name + " = true");
        line(name + "_top = " + name + "_g");
        indent--;
        line("end");
        indent--;
        line("end");
        indent--;
        line("end");
    }

    private String column(int c) {
        return switch (c) {
            case FxVm.COL_PX -> "px";
            case FxVm.COL_PY -> "py";
            case FxVm.COL_PZ -> "pz";
            case FxVm.COL_VX -> "vx";
            case FxVm.COL_VY -> "vy";
            case FxVm.COL_VZ -> "vz";
            case FxVm.COL_AGE -> "age";
            case FxVm.COL_INVLIFE -> "inv_life";
            case FxVm.COL_ROT -> "rot";
            case FxVm.COL_SPIN -> "spin";
            case FxVm.COL_SIZE0 -> "size0";
            case FxVm.COL_SIZE1 -> "size1";
            default -> "c" + (c - FxVm.BUILTIN_COLUMNS);
        };
    }

